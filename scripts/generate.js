import { dump } from "js-yaml";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
	buildConfig,
	schemaToFile,
	stripConstraints,
	TARGETS,
} from "./build.js";

const overrides = {
	activityGroups: { textFields: ["modalContent"] },
	leadership: { labelSingular: "Leader" },
	alumni: { labelSingular: "Alumnus" },
};

const args = process.argv.slice(2);
const minimal = args.includes("--minimal");
const [dir = "src/data/schemas", outDir = "public/admin"] = args.filter(
	(a) => !a.startsWith("--")
);

const files = readdirSync(dir)
	.filter((f) => f.endsWith(".schema.json"))
	.sort()
	.map((f) => {
		const name = f.replace(/\.schema\.json$/, "");
		const schema = JSON.parse(readFileSync(join(dir, f), "utf8"));
		return schemaToFile(name, schema, overrides[name]);
	});

mkdirSync(outDir, { recursive: true });
for (const target of Object.keys(TARGETS)) {
	const out = join(outDir, target);
	const built = buildConfig(files, target);
	const config = minimal ? stripConstraints(built) : built;
	writeFileSync(
		out,
		"# GENERATED by generate.js. Do not edit by hand.\n" +
			dump(config, { lineWidth: -1, noRefs: true })
	);
	console.log(`Wrote ${out} (${files.length} collections)`);
}
