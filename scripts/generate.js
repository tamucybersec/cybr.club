import { createHash } from "node:crypto";
import {
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import nextEnv from "@next/env";
import { contentSource } from "./content-source.mjs";
import {
	buildConfig,
	getBackend,
	schemaToFile,
	stripConstraints,
	TARGETS,
} from "./build.js";

const overrides = {
	activityGroups: { textFields: ["modalContent"] },
	leadership: { labelSingular: "Leader" },
	alumni: { labelSingular: "Alumnus" },
};

const args = process.argv.slice(2);
const development =
	args.includes("--development") || process.env.NODE_ENV === "development";
nextEnv.loadEnvConfig(process.cwd(), development);
const source = contentSource(process.env, development);
const targets = Object.keys(TARGETS).filter(
	(target) =>
		target !== "config.local.yml" || development || source.target === "test"
);
const minimal = args.includes("--minimal");
const force = args.includes("--force");
const [dir = "src/data/schemas", outDir = "public/admin"] = args.filter(
	(a) => !a.startsWith("--")
);

// A build after local development must not export a stale test config.
for (const target of Object.keys(TARGETS)) {
	if (!targets.includes(target)) {
		rmSync(join(outDir, target), { force: true });
	}
}

const hash = (value) => createHash("sha256").update(value).digest("hex");
const schemas = readdirSync(dir)
	.filter((f) => f.endsWith(".schema.json"))
	.sort()
	.map((name) => [name, readFileSync(join(dir, name), "utf8")]);

// Include implementation and dependency changes, not just schema timestamps.
const fingerprint = hash(
	JSON.stringify({
		minimal,
		targets,
		backends: targets.map((target) => getBackend(target)),
		schemas,
		generator: readFileSync(new URL(import.meta.url), "utf8"),
		builder: readFileSync(new URL("./build.js", import.meta.url), "utf8"),
		lockfile: readFileSync(
			new URL("../package-lock.json", import.meta.url),
			"utf8"
		),
	})
);
const cacheDir = "node_modules/.cache/cybr-club";
const cacheFile = join(cacheDir, `cms-${hash(resolve(outDir))}.json`);

let cached;
try {
	cached = JSON.parse(readFileSync(cacheFile, "utf8"));
} catch {
	// A missing or invalid cache is rebuilt automatically.
}

let upToDate = !force && cached?.fingerprint === fingerprint;
if (upToDate) {
	try {
		upToDate = targets.every(
			(target) =>
				hash(readFileSync(join(outDir, target))) ===
				cached.outputs?.[target]
		);
	} catch {
		upToDate = false;
	}
}

if (upToDate) {
	console.log("CMS configs are up to date; skipped generation.");
} else {
	// Avoid loading the YAML serializer on the usual, unchanged startup.
	const { dump } = await import("js-yaml");
	const files = schemas.map(([filename, text]) => {
		const name = filename.replace(/\.schema\.json$/, "");
		return schemaToFile(name, JSON.parse(text), overrides[name]);
	});

	mkdirSync(outDir, { recursive: true });
	const outputs = {};
	for (const target of targets) {
		const out = join(outDir, target);
		const built = buildConfig(files, target);
		const config = minimal ? stripConstraints(built) : built;
		const content =
			"# GENERATED by generate.js. Do not edit by hand.\n" +
			dump(config, { lineWidth: -1, noRefs: true });
		outputs[target] = hash(content);

		let existing;
		try {
			existing = readFileSync(out, "utf8");
		} catch (error) {
			if (error.code !== "ENOENT") throw error;
		}
		if (existing === content) {
			console.log(`Unchanged ${out}`);
		} else {
			writeFileSync(out, content);
			console.log(`Wrote ${out} (${files.length} collections)`);
		}
	}

	mkdirSync(cacheDir, { recursive: true });
	writeFileSync(cacheFile, JSON.stringify({ fingerprint, outputs }) + "\n");
}
